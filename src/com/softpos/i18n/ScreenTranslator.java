package com.softpos.i18n;

import com.softpos.util.AppLogUtil;
import java.awt.AWTEvent;
import java.awt.Component;
import java.awt.Container;
import java.awt.Dialog;
import java.awt.Frame;
import java.awt.Toolkit;
import java.awt.Window;
import java.awt.event.WindowEvent;
import java.lang.reflect.Field;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.MissingResourceException;
import java.util.ResourceBundle;
import javax.swing.AbstractButton;
import javax.swing.JComponent;
import javax.swing.JInternalFrame;
import javax.swing.JLabel;
import javax.swing.JMenu;
import javax.swing.JPopupMenu;
import javax.swing.JTabbedPane;
import javax.swing.JTable;
import javax.swing.UIManager;
import javax.swing.border.Border;
import javax.swing.border.CompoundBorder;
import javax.swing.border.TitledBorder;
import javax.swing.table.TableColumn;

/**
 * Translates designer (.form) texts of every window without per-screen code.
 *
 * The Thai text itself is the key: com/softpos/i18n/screen_{lang}.properties maps
 * "Thai text=translation" (generated by ExtractScreenTexts). When a window opens, its labels,
 * buttons, menus, titles, tooltips, titled borders, tabs and table headers are looked up there;
 * texts without a translation (or with an empty one) stay Thai. Thai screens are left untouched.
 * Only texts present at WINDOW_OPENED are translated; texts set later in code need Lang.get().
 * Messages shown through MSG use translateMessage with com/softpos/i18n/message_{lang}.properties.
 */
public class ScreenTranslator {

    private static final String SCREEN_BUNDLE = "com.softpos.i18n.screen";
    private static final String MESSAGE_BUNDLE = "com.softpos.i18n.message";

    private static ResourceBundle screenTexts;
    private static ResourceBundle messageTexts;
    // message keys with a translation, longest first, for messages built by concatenation
    private static List<String> messageFragments = new ArrayList<>();
    private static Locale loadedFor;

    private ScreenTranslator() {
    }

    /** Call once at startup, before the first window opens. */
    public static void install() {
        if (isThai()) {
            return;
        }
        UIManager.put("OptionPane.okButtonText", Lang.get("optionPane.ok"));
        UIManager.put("OptionPane.cancelButtonText", Lang.get("optionPane.cancel"));
        UIManager.put("OptionPane.yesButtonText", Lang.get("optionPane.yes"));
        UIManager.put("OptionPane.noButtonText", Lang.get("optionPane.no"));
        Toolkit.getDefaultToolkit().addAWTEventListener(e -> {
            if (e.getID() == WindowEvent.WINDOW_OPENED) {
                translateWindow(((WindowEvent) e).getWindow());
            }
        }, AWTEvent.WINDOW_EVENT_MASK);
    }

    private static boolean isThai() {
        return Lang.THAI.getLanguage().equals(Lang.getLocale().getLanguage());
    }

    /** Loads both bundles for the current language; false for Thai or when there is no screen translation. */
    private static synchronized boolean load() {
        Locale locale = Lang.getLocale();
        if (!locale.equals(loadedFor)) {
            loadedFor = locale;
            screenTexts = null;
            messageTexts = null;
            messageFragments = new ArrayList<>();
            if (!isThai()) {
                screenTexts = loadBundle(SCREEN_BUNDLE, locale);
                messageTexts = loadBundle(MESSAGE_BUNDLE, locale);
                if (messageTexts != null) {
                    for (String key : messageTexts.keySet()) {
                        if (!messageTexts.getString(key).isEmpty()) {
                            messageFragments.add(key);
                        }
                    }
                    messageFragments.sort((a, b) -> b.length() - a.length());
                }
            }
        }
        return screenTexts != null || messageTexts != null;
    }

    private static ResourceBundle loadBundle(String name, Locale locale) {
        try {
            return ResourceBundle.getBundle(name, locale, new Lang.UTF8Control());
        } catch (MissingResourceException e) {
            AppLogUtil.info(ScreenTranslator.class, "No translation " + name + " for language '" + locale + "'");
            return null;
        }
    }

    /** The window, its menus and the popup menus it holds in fields (designer non-visual components). */
    public static void translateWindow(Window w) {
        if (!load()) {
            return;
        }
        if (w instanceof Dialog) {
            ((Dialog) w).setTitle(translate(((Dialog) w).getTitle()));
        } else if (w instanceof Frame) {
            ((Frame) w).setTitle(translate(((Frame) w).getTitle()));
        }
        translateTree(w);
        for (JPopupMenu popup : popupMenuFields(w)) {
            translateTree(popup);
        }
        Lang.applyFont(w);
    }

    /** Translation of a whole screen text, keeping its surrounding spaces; the text itself if none. */
    public static String translate(String text) {
        if (text == null || !hasThai(text) || !load()) {
            return text;
        }
        String key = text.trim();
        String value = lookup(screenTexts, key);
        if (value.isEmpty()) {
            value = lookup(messageTexts, key);
        }
        if (value.isEmpty()) {
            return text;
        }
        int start = text.indexOf(key);
        return text.substring(0, start) + value + text.substring(start + key.length());
    }

    /**
     * Translation of a message shown by code (MSG, JOptionPane). Messages are often built as
     * "Thai text " + value + " Thai text", so when the whole text is not a key each known
     * fragment is replaced, longest first; untranslated parts stay Thai.
     */
    public static String translateMessage(String text) {
        String whole = translate(text);
        if (whole == null || !whole.equals(text) || !hasThai(text)) {
            return whole;
        }
        String result = text;
        for (String key : messageFragments) {
            if (result.contains(key)) {
                result = result.replace(key, messageTexts.getString(key));
            }
        }
        return result;
    }

    private static String lookup(ResourceBundle b, String key) {
        return b != null && b.containsKey(key) ? b.getString(key) : "";
    }

    static boolean hasThai(String s) {
        for (int i = 0; i < s.length(); i++) {
            char ch = s.charAt(i);
            if (ch >= '\u0E00' && ch <= '\u0E7F') {
                return true;
            }
        }
        return false;
    }

    private static void translateTree(Component c) {
        if (c instanceof AbstractButton) {
            AbstractButton b = (AbstractButton) c;
            b.setText(translate(b.getText()));
        } else if (c instanceof JLabel) {
            JLabel l = (JLabel) c;
            l.setText(translate(l.getText()));
        } else if (c instanceof JInternalFrame) {
            JInternalFrame f = (JInternalFrame) c;
            f.setTitle(translate(f.getTitle()));
        } else if (c instanceof JTabbedPane) {
            JTabbedPane tabs = (JTabbedPane) c;
            for (int i = 0; i < tabs.getTabCount(); i++) {
                tabs.setTitleAt(i, translate(tabs.getTitleAt(i)));
                tabs.setToolTipTextAt(i, translate(tabs.getToolTipTextAt(i)));
            }
        } else if (c instanceof JTable) {
            translateHeaders((JTable) c);
        }
        if (c instanceof JComponent) {
            JComponent jc = (JComponent) c;
            String tip = jc.getToolTipText();
            if (tip != null) {
                jc.setToolTipText(translate(tip));
            }
            translateBorder(jc, jc.getBorder());
            if (jc.getComponentPopupMenu() != null) {
                translateTree(jc.getComponentPopupMenu());
            }
        }
        if (c instanceof JMenu) {
            for (Component item : ((JMenu) c).getMenuComponents()) {
                translateTree(item);
            }
        }
        if (c instanceof Container) {
            for (Component child : ((Container) c).getComponents()) {
                translateTree(child);
            }
        }
    }

    private static void translateHeaders(JTable table) {
        boolean changed = false;
        for (int i = 0; i < table.getColumnModel().getColumnCount(); i++) {
            TableColumn col = table.getColumnModel().getColumn(i);
            if (col.getHeaderValue() instanceof String) {
                String old = (String) col.getHeaderValue();
                String text = translate(old);
                if (!text.equals(old)) {
                    col.setHeaderValue(text);
                    changed = true;
                }
            }
        }
        if (changed && table.getTableHeader() != null) {
            table.getTableHeader().repaint();
        }
    }

    private static void translateBorder(JComponent c, Border border) {
        if (border instanceof TitledBorder) {
            TitledBorder tb = (TitledBorder) border;
            String text = translate(tb.getTitle());
            if (text != null && !text.equals(tb.getTitle())) {
                tb.setTitle(text);
                c.repaint();
            }
        } else if (border instanceof CompoundBorder) {
            translateBorder(c, ((CompoundBorder) border).getOutsideBorder());
            translateBorder(c, ((CompoundBorder) border).getInsideBorder());
        }
    }

    // Designer popup menus are not in the component tree until shown, only in fields of the window class
    private static List<JPopupMenu> popupMenuFields(Window w) {
        List<JPopupMenu> popups = new ArrayList<>();
        for (Class<?> cls = w.getClass(); cls != null && !cls.getName().startsWith("java"); cls = cls.getSuperclass()) {
            for (Field f : cls.getDeclaredFields()) {
                if (JPopupMenu.class.isAssignableFrom(f.getType())) {
                    try {
                        f.setAccessible(true);
                        Object value = f.get(w);
                        if (value != null) {
                            popups.add((JPopupMenu) value);
                        }
                    } catch (ReflectiveOperationException | RuntimeException e) {
                        AppLogUtil.log(ScreenTranslator.class, "error", e);
                    }
                }
            }
        }
        return popups;
    }
}
